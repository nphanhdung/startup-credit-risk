def assign_industry_group(category_list: pd.Series) -> pd.Series:
    """Return the industry group for each company's pipe-separated category list."""
    categories = category_list.fillna("").astype(str)
    result = pd.Series("Other", index=categories.index, dtype="object")
    unassigned = pd.Series(True, index=categories.index)
    for group, keywords in INDUSTRY_KEYWORDS.items():
        pattern = "|".join(re.escape(k) for k in keywords)
        matches = unassigned & categories.str.contains(pattern, case=False, regex=True)
        result[matches] = group
        unassigned &= ~matches
    return result
